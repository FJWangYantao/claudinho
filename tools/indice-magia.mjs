// Builds the index of the ASCII Magic pieces (name, category, note, tags,
// size) the app searches and offers as backgrounds, from the categories kept
// below. Run it again after changing them or updating ascii-magic-art:
//   node tools/indice-magia.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const raiz = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const pacote = path.join(raiz, "node_modules", "ascii-magic-art");
// Only these categories are offered in the app (and to Claude).
const MANTER = new Set(["landscapes", "cities", "cosmos", "weather", "animals", "algorithms", "arcade", "occasions", "mascots"]);
const cats = JSON.parse(fs.readFileSync(path.join(pacote, "categories.json"), "utf8")).filter((c) => MANTER.has(c.id)).map((c) => [c.id, c.name]);
const pecas = [];
for (const f of fs.readdirSync(path.join(pacote, "pieces")).filter((f) => f.endsWith(".js")).sort()) {
  try {
    const { meta } = await import(pathToFileURL(path.join(pacote, "pieces", f)).href);
    if (!MANTER.has(meta.category)) continue;
    // [slug, name, category, note, tags, cols, rows, square cells]
    pecas.push([meta.slug, meta.name, meta.category, meta.note || "", (meta.tags || []).join(" "), meta.cols, meta.rows, meta.cell === "square" ? 1 : 0]);
  } catch (e) { console.warn("pulou", f, e.message); }
}
const destino = path.join(raiz, "src", "renderer", "wallpapers", "magia-indice.js");
fs.writeFileSync(destino, `// Generated by tools/indice-magia.mjs from ascii-magic-art (MIT). Do not edit.\nwindow.MAGIA = ${JSON.stringify({ cats, pecas })};\n`);
console.log(`${pecas.length} peças, ${cats.length} categorias -> ${path.relative(raiz, destino)}`);
